@torch.no_grad()
def visualize_test_windows(
    model: nn.Module,
    test_ds: SAR_RARP50SegmentDataset,
    selected_prompts,
    args,
    device: torch.device,
    test_split_set: str,
    decision_threshold: float = 0.5,
):
    os.makedirs(args.vis_outdir, exist_ok=True)
    _save_prompts(os.path.join(args.vis_outdir, "prompts.txt"), selected_prompts)
    rng = random.Random(args.vis_seed)

    model.eval()
    saved = 0
    for idx in range(len(test_ds)):
        if rng.random() > args.vis_ratio:
            continue
        if args.vis_max_windows and saved >= args.vis_max_windows:
            break

        vid, start = test_ds.indices[idx]
        item = test_ds[idx]
        if item is None:
            continue
        feats, label, _ = item
        t = int(feats.size(0))
        if t <= 0:
            continue
        masks = (torch.arange(t).unsqueeze(0) < torch.tensor([t]).unsqueeze(1)).to(device)
        feats = feats.unsqueeze(0).to(device)
        out = model(feats, masks=masks, return_attn=True)
        logits, attn_weights = out
        prob = float(torch.sigmoid(logits).squeeze().item())

        attn = attn_weights.squeeze(0).detach().cpu().numpy()[:, :t]
        gt = int(label.item()) if hasattr(label, "item") else int(label)
        errors = [gt for _ in range(t)]
        frame_nums = [start + i for i in range(t)]

        base_name = f"{vid}_idx{idx}_s{start}_len{t}"
        attn_path = os.path.join(args.vis_outdir, f"{base_name}_attn.png")
        frames_path = os.path.join(args.vis_outdir, f"{base_name}_frames.png")
        meta_path = os.path.join(args.vis_outdir, f"{base_name}_meta.json")
        _save_attention_figure(attn_path, attn, frame_nums, errors, prob)

        frames = []
        for fn in frame_nums:
            img = _load_frame(
                args.data_root,
                test_split_set,
                vid,
                fn,
                frame_file_stride=int(args.frame_file_stride),
                frame_index_base=int(args.frame_index_base),
            )
            if img is not None:
                frames.append(img)
        _save_frames_grid(frames_path, frames)

        pred = int(prob >= float(decision_threshold))
        with open(meta_path, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "video_id": vid,
                    "start": int(start),
                    "frames": int(t),
                    "gt_label": gt,
                    "pred_label": pred,
                    "pred_prob": prob,
                    "decision_threshold": float(decision_threshold),
                },
                f,
                indent=2,
            )
        saved += 1




def _selection_score(f1, bal_acc, metric):
    """
    Score used to pick the best epoch (and drive early stopping).

    Plain F1 is gameable on these imbalanced window datasets: a near-constant
    "always error" predictor scores high F1 at chance-level balanced accuracy, so
    selecting on F1 alone lands on a positive-leaning epoch. `f1_bacc` averages F1
    with balanced accuracy and is the criterion the tuning campaign used, so it is
    the default here as well.
    """
    if metric == "f1":
        return f1
    if metric == "bacc":
        return bal_acc
    if metric == "f1_bacc":
        return 0.5 * (f1 + bal_acc)
    raise ValueError(f"Unknown selection_metric: {metric!r}")


