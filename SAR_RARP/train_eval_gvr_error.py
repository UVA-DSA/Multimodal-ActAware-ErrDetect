def _infer_feature_dim(ds: SAR_RARP50SegmentDataset) -> int:
    for i in range(min(len(ds), 200)):
        item = ds[i]
        if item is None:
            continue
        x, _y, _vid = item
        return int(x.size(-1))
    raise RuntimeError("Could not infer feature dim (dataset returned only None).")


def _ensure_dir(path: str) -> None:
    os.makedirs(path, exist_ok=True)


def _save_prompts(path: str, prompts) -> None:
    with open(path, "w", encoding="utf-8") as f:
        for i, p in enumerate(prompts):
            f.write(f"{i}\t{p}\n")


def _load_frame(
    data_root: str,
    split_set: str,
    video_name: str,
    logical_frame_idx: int,
    frame_file_stride: int = 12,
    frame_index_base: int = 0,
) -> Optional[Image.Image]:
    frame_idx = int(logical_frame_idx) * int(frame_file_stride) + int(frame_index_base)
    frame_path = os.path.join(data_root, split_set, video_name, "images", f"{frame_idx:09d}.png")
    if not os.path.exists(frame_path):
        return None
    return Image.open(frame_path).convert("RGB")


